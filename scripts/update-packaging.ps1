#!/usr/bin/env pwsh
# Regenerate the winget, Scoop and Homebrew manifests from a GitHub release.
#
# Usage:
#   ./scripts/update-packaging.ps1 -Version 1.8.0
#
# The script reads the release assets and their SHA-256 digests from the
# GitHub API (gh CLI), then rewrites:
#   packaging/winget/manifests/p/purelogiccode/XISOSharp/<version>/*.yaml
#   packaging/scoop/xisosharp.json
#   packaging/homebrew/xisosharp.rb
#
# Older winget version directories are left in place (manifest repositories
# keep every published version). Run this before tagging a release, or right
# after the release workflow uploads the bundles.

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string] $Version,

    [string] $Repo = 'purelogiccode/XISOSharp'
)

$ErrorActionPreference = 'Stop'

$version = $Version.TrimStart('v')
$repoRoot = Split-Path -Parent $PSScriptRoot
$rids = @('win-x64', 'win-arm64', 'linux-x64', 'linux-arm64', 'MacOsX-x64', 'MacOsX-arm64')

Write-Host "Reading release $version from $Repo..."
$release = gh release view $version --repo $Repo --json 'tagName,assets' | ConvertFrom-Json
$hashes = @{}
foreach ($asset in $release.assets) {
    if ($asset.digest -and $asset.digest.StartsWith('sha256:', [StringComparison]::Ordinal)) {
        $hashes[$asset.name] = $asset.digest.Substring('sha256:'.Length)
    }
}

foreach ($rid in $rids) {
    $asset = "release_${version}_${rid}.zip"
    if (-not $hashes.ContainsKey($asset)) {
        throw "Release asset $asset has no SHA-256 digest. Publish the bundles before generating manifests."
    }
}

$winX64 = $hashes["release_${version}_win-x64.zip"]
$winArm64 = $hashes["release_${version}_win-arm64.zip"]
$macX64 = $hashes["release_${version}_MacOsX-x64.zip"]
$macArm64 = $hashes["release_${version}_MacOsX-arm64.zip"]

# ---------------------------------------------------------------- winget ----
$wingetDir = Join-Path $repoRoot "packaging/winget/manifests/p/purelogiccode/XISOSharp/$version"
New-Item -ItemType Directory -Force -Path $wingetDir | Out-Null

$wingetVersion = @"
# Generated by scripts/update-packaging.ps1.
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.version.1.10.0.schema.json
PackageIdentifier: purelogiccode.XISOSharp
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.10.0
"@

$wingetInstaller = @"
# Generated by scripts/update-packaging.ps1.
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.installer.1.10.0.schema.json
PackageIdentifier: purelogiccode.XISOSharp
PackageVersion: $version
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: XISOSharp.exe
    PortableCommandAlias: xisosharp
  - RelativeFilePath: XISOSharp.Gui.exe
    PortableCommandAlias: xisosharp-gui
Installers:
  - Architecture: x64
    InstallerUrl: https://github.com/$Repo/releases/download/$version/release_${version}_win-x64.zip
    InstallerSha256: $($winX64.ToUpperInvariant())
  - Architecture: arm64
    InstallerUrl: https://github.com/$Repo/releases/download/$version/release_${version}_win-arm64.zip
    InstallerSha256: $($winArm64.ToUpperInvariant())
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Microsoft.DotNet.DesktopRuntime.10
      MinimumVersion: 10.0.0
ManifestType: installer
ManifestVersion: 1.10.0
"@

$wingetLocale = @"
# Generated by scripts/update-packaging.ps1.
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.defaultLocale.1.10.0.schema.json
PackageIdentifier: purelogiccode.XISOSharp
PackageVersion: $version
PackageLocale: en-US
Publisher: purelogiccode
PublisherUrl: https://github.com/purelogiccode
PublisherSupportUrl: https://github.com/$Repo/issues
Author: purelogiccode
PackageName: XISOSharp
PackageUrl: https://github.com/$Repo
License: MIT
LicenseUrl: https://github.com/$Repo/blob/master/LICENSE
Copyright: Copyright (c) purelogiccode
ShortDescription: Create, extract, list, rewrite and archive Xbox XISO/XDVDFS disc images.
Description: A pure C# extract-xiso port with XboxKit Redump archival modes, xdvdfs packing/CISO support, CCI and ZAR containers, read-only GOD/SVOD and XBLA/XBLIG STFS readers, and an Avalonia desktop front-end.
Moniker: xisosharp
Tags:
  - xiso
  - xbox
  - xbox-360
  - iso
  - extract-xiso
  - xdvdfs
  - redump
  - ciso
  - cci
  - zar
  - god
  - stfs
  - disc-image
ReleaseNotesUrl: https://github.com/$Repo/releases/tag/$version
ManifestType: defaultLocale
ManifestVersion: 1.10.0
"@

Set-Content -LiteralPath (Join-Path $wingetDir 'purelogiccode.XISOSharp.yaml') -Value $wingetVersion -Encoding utf8NoBOM
Set-Content -LiteralPath (Join-Path $wingetDir 'purelogiccode.XISOSharp.installer.yaml') -Value $wingetInstaller -Encoding utf8NoBOM
Set-Content -LiteralPath (Join-Path $wingetDir 'purelogiccode.XISOSharp.locale.en-US.yaml') -Value $wingetLocale -Encoding utf8NoBOM
Write-Host "winget: wrote $wingetDir"

# ----------------------------------------------------------------- scoop ----
$scoopDir = Join-Path $repoRoot 'packaging/scoop'
New-Item -ItemType Directory -Force -Path $scoopDir | Out-Null

$scoop = [ordered]@{
    '$schema'     = 'https://raw.githubusercontent.com/ScoopInstaller/Scoop/master/schema.json'
    version       = $version
    description   = 'Create, extract, list, rewrite and archive Xbox XISO/XDVDFS disc images.'
    homepage      = "https://github.com/$Repo"
    license       = 'MIT'
    depends       = 'dotnet-sdk'
    architecture  = [ordered]@{
        '64bit' = [ordered]@{
            url  = "https://github.com/$Repo/releases/download/$version/release_${version}_win-x64.zip"
            hash = $winX64
        }
        'arm64' = [ordered]@{
            url  = "https://github.com/$Repo/releases/download/$version/release_${version}_win-arm64.zip"
            hash = $winArm64
        }
    }
    bin           = @(
        'XISOSharp.exe',
        @('XISOSharp.Gui.exe', 'xisosharp-gui')
    )
    shortcuts     = @(
        , @('XISOSharp.Gui.exe', 'XISOSharp')
    )
    checkver      = [ordered]@{
        github = "https://github.com/$Repo"
        regex  = 'release_([\d.]+)_win-x64\.zip'
    }
    autoupdate    = [ordered]@{
        architecture = [ordered]@{
            '64bit' = [ordered]@{
                url = "https://github.com/$Repo/releases/download/`$version/release_`$version_win-x64.zip"
            }
            'arm64' = [ordered]@{
                url = "https://github.com/$Repo/releases/download/`$version/release_`$version_win-arm64.zip"
            }
        }
    }
}

$scoop | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $scoopDir 'xisosharp.json') -Encoding utf8NoBOM
Write-Host "scoop: wrote $scoopDir/xisosharp.json"

# The repository root doubles as a Scoop bucket: Scoop expects `bucket/<app>.json`.
$bucketDir = Join-Path $repoRoot 'bucket'
New-Item -ItemType Directory -Force -Path $bucketDir | Out-Null
Copy-Item -LiteralPath (Join-Path $scoopDir 'xisosharp.json') -Destination (Join-Path $bucketDir 'xisosharp.json') -Force
Write-Host "scoop: wrote $bucketDir/xisosharp.json (bucket root)"

# -------------------------------------------------------------- homebrew ----
$homebrewDir = Join-Path $repoRoot 'packaging/homebrew'
New-Item -ItemType Directory -Force -Path $homebrewDir | Out-Null

$cask = @'
# Generated by scripts/update-packaging.ps1.
cask "xisosharp" do
  version "__VERSION__"

  on_arm do
    url "https://github.com/__REPO__/releases/download/#{version}/release_#{version}_MacOsX-arm64.zip"
    sha256 "__MACARM64__"
  end

  on_intel do
    url "https://github.com/__REPO__/releases/download/#{version}/release_#{version}_MacOsX-x64.zip"
    sha256 "__MACX64__"
  end

  name "XISOSharp"
  desc "Create, extract, list, rewrite and archive Xbox XISO/XDVDFS disc images"
  homepage "https://github.com/__REPO__"

  depends_on formula: "dotnet"
  depends_on macos: ">= :monterey"

  binary "XISOSharp", target: "xisosharp"
  binary "XISOSharp.Gui", target: "xisosharp-gui"
end
'@

$cask = $cask.Replace('__VERSION__', $version).
    Replace('__REPO__', $Repo).
    Replace('__MACARM64__', $macArm64).
    Replace('__MACX64__', $macX64)

Set-Content -LiteralPath (Join-Path $homebrewDir 'xisosharp.rb') -Value $cask -Encoding utf8NoBOM
Write-Host "homebrew: wrote $homebrewDir/xisosharp.rb"

Write-Host "Done. Review the manifests, then submit them to the package repositories."
